//! Generating the proxy configuration (a Caddyfile) from the registry.
//!
//! One wildcard site `*.<base>` gets the single wildcard certificate (DNS-01 through
//! Cloudflare). Each route is a `handle` block matched on its host name, so adding or removing
//! a route never changes which certificate is needed.

use crate::names;
use crate::registry::Route;
use anyhow::Result;
use std::net::Ipv4Addr;
use std::path::Path;

pub struct Settings<'a> {
    pub base_domain: &'a str,
    pub port: u16,
    /// The tailnet IPv4: the only address the proxy binds.
    pub bind_ip: Ipv4Addr,
    pub admin_socket: &'a Path,
    pub storage_dir: &'a Path,
    pub acme_ca: Option<&'a str>,
    /// Reject requests from outside the Tailscale address ranges before any route.
    pub restrict_source: bool,
}

/// What `restrict_source` lets through, in Caddy `remote_ip` syntax.
const TAILNET_RANGES: &str = "100.64.0.0/10 fd7a:115c:a1e0::/48";

/// A named matcher for every request whose peer address is outside the tailnet ranges. It is the
/// TCP peer (`remote_ip`), never a forwarded header.
const OUTSIDE_MATCHER: &str = "@outside not remote_ip";

/// A Caddyfile token in double quotes. A control character (a newline would start a new
/// directive) is an error.
fn quote(s: &str) -> Result<String> {
    names::reject_control("a value for the Caddyfile", s)?;
    Ok(format!(
        "\"{}\"",
        s.replace('\\', "\\\\").replace('"', "\\\"")
    ))
}

/// Names (`routes`, `base_domain`) are validated when loaded; paths and the CA are checked here.
pub fn generate(s: &Settings, routes: &[Route]) -> Result<String> {
    let mut out = String::new();
    out.push_str("# Generated by bsjn from routes.json. Do not edit.\n{\n");
    out.push_str(&format!(
        "\tadmin {}\n",
        quote(&format!("unix/{}|0600", s.admin_socket.display()))?
    ));
    out.push_str("\tpersist_config off\n");
    out.push_str(&format!("\tdefault_bind {}\n", s.bind_ip));
    out.push_str(&format!("\thttps_port {}\n", s.port));
    out.push_str("\tauto_https disable_redirects\n");
    out.push_str(&format!(
        "\tstorage file_system {}\n",
        quote(&s.storage_dir.display().to_string())?
    ));
    out.push_str("}\n\n");

    out.push_str(&format!("*.{} {{\n", s.base_domain));
    out.push_str("\ttls {\n");
    if let Some(ca) = s.acme_ca {
        out.push_str(&format!("\t\tca {}\n", quote(ca)?));
    }
    out.push_str("\t\tdns cloudflare {env.CLOUDFLARE_API_TOKEN}\n\t}\n");

    if s.restrict_source {
        // First, so it runs before every route, the unknown-host 404 included. `handle` (not a
        // bare `abort`) because Caddy orders `handle` before `abort`.
        out.push_str(&format!(
            "\t{OUTSIDE_MATCHER} {TAILNET_RANGES}\n\thandle @outside {{\n\t\tabort\n\t}}\n"
        ));
    }

    for r in routes {
        let host = names::host(&r.name, s.base_domain);
        out.push_str(&format!(
            "\t@r_{} host {host}\n\thandle @r_{} {{\n\t\treverse_proxy 127.0.0.1:{}\n\t}}\n",
            r.name, r.name, r.port
        ));
    }
    out.push_str("\thandle {\n\t\trespond \"bsjn: no route for {host}\" 404\n\t}\n");

    out.push_str("\thandle_errors {\n");
    if s.restrict_source {
        // Error pages (the 502 "nothing is listening" page) are not shown to outsiders either.
        out.push_str("\t\tabort @outside\n");
    }
    for r in routes {
        let host = names::host(&r.name, s.base_domain);
        out.push_str(&format!(
            "\t\t@down_{} {{\n\t\t\thost {host}\n\t\t\texpression {{http.error.status_code}} == 502\n\t\t}}\n",
            r.name
        ));
        out.push_str(&format!(
            "\t\trespond @down_{} \"bsjn: nothing is listening on port {} for {}\" 502\n",
            r.name, r.port, r.name
        ));
    }
    out.push_str("\t}\n}\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry::Kind;
    use std::path::PathBuf;

    fn route(name: &str, port: u16) -> Route {
        Route {
            name: name.into(),
            port,
            kind: Kind::Persistent,
            tag: None,
            pid: None,
            start_time: None,
        }
    }

    fn settings<'a>(admin: &'a Path, storage: &'a Path) -> Settings<'a> {
        Settings {
            base_domain: "dev.example.com",
            port: 8443,
            bind_ip: Ipv4Addr::new(100, 64, 0, 1),
            admin_socket: admin,
            storage_dir: storage,
            acme_ca: None,
            restrict_source: true,
        }
    }

    #[test]
    fn binds_only_the_given_ip_and_never_a_wildcard_address() {
        let (a, s) = (PathBuf::from("/s/admin.sock"), PathBuf::from("/s/caddy"));
        let text = generate(&settings(&a, &s), &[]).unwrap();
        assert!(text.contains("\tdefault_bind 100.64.0.1\n"));
        assert!(text.contains("\thttps_port 8443\n"));
        assert!(!text.contains("0.0.0.0"));
        assert!(text.contains("admin \"unix//s/admin.sock|0600\""));
        assert!(text.contains("*.dev.example.com {"));
    }

    #[test]
    fn the_token_is_a_placeholder_never_a_value() {
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let text = generate(&settings(&a, &s), &[]).unwrap();
        assert!(text.contains("dns cloudflare {env.CLOUDFLARE_API_TOKEN}"));
    }

    #[test]
    fn every_route_gets_a_host_match_a_proxy_and_a_down_page() {
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let text = generate(&settings(&a, &s), &[route("web", 5173), route("api", 3000)]).unwrap();
        assert!(text.contains("@r_web host web.dev.example.com"));
        assert!(text.contains("handle @r_web {\n\t\treverse_proxy 127.0.0.1:5173\n"));
        assert!(text.contains("@r_api host api.dev.example.com"));
        assert!(text.contains("reverse_proxy 127.0.0.1:3000"));
        assert!(
            text.contains(
                "respond @down_web \"bsjn: nothing is listening on port 5173 for web\" 502"
            )
        );
        assert!(text.contains("respond \"bsjn: no route for {host}\" 404"));
    }

    #[test]
    fn a_custom_ca_goes_into_the_tls_block() {
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let mut st = settings(&a, &s);
        st.acme_ca = Some("https://acme.example/dir");
        assert!(
            generate(&st, &[])
                .unwrap()
                .contains("\t\tca \"https://acme.example/dir\"\n")
        );
    }

    #[test]
    fn paths_with_quotes_are_escaped() {
        assert_eq!(quote("a\"b\\c").unwrap(), "\"a\\\"b\\\\c\"");
    }

    #[test]
    fn a_newline_in_a_path_or_the_ca_cannot_inject_directives() {
        let (a, s) = (PathBuf::from("/a\nbind 0.0.0.0"), PathBuf::from("/s"));
        assert!(generate(&settings(&a, &s), &[]).is_err());
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s\r}"));
        assert!(generate(&settings(&a, &s), &[]).is_err());
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let mut st = settings(&a, &s);
        st.acme_ca = Some("https://x\n}");
        assert!(generate(&st, &[]).is_err());
    }

    #[test]
    fn requests_from_outside_the_tailnet_are_aborted_before_any_route() {
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let text = generate(&settings(&a, &s), &[route("web", 5173)]).unwrap();
        let guard = "@outside not remote_ip 100.64.0.0/10 fd7a:115c:a1e0::/48\n\thandle @outside {\n\t\tabort\n\t}\n";
        let at = |needle: &str| {
            text.find(needle)
                .unwrap_or_else(|| panic!("{needle}\n{text}"))
        };
        // Before the host routes and before the catch-all 404 page...
        assert!(at(guard) < at("@r_web host"));
        assert!(at(guard) < at("respond \"bsjn: no route"));
        // ...and the 502 page is guarded as well.
        assert!(at("abort @outside") < at("respond @down_web"));
        assert!(at("abort @outside") > at("handle_errors {"));
        assert_eq!(text.matches("remote_ip").count(), 1, "one matcher, reused");
    }

    #[test]
    fn the_source_restriction_can_be_switched_off() {
        let (a, s) = (PathBuf::from("/a"), PathBuf::from("/s"));
        let mut st = settings(&a, &s);
        st.restrict_source = false;
        let text = generate(&st, &[route("web", 5173)]).unwrap();
        assert!(
            !text.contains("remote_ip") && !text.contains("abort"),
            "{text}"
        );
    }
}
